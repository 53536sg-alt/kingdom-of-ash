  // ترقية الحفظات القديمة كي لا ينكسر أي رقم.
  function epiState(s) {
    s = s || (A.game && A.game.state);
    if (!s) return null;
    if (!s.postQuests) s.postQuests = {};
    if (!s.postProgress) s.postProgress = {};
    if (!s.flags) s.flags = {};
    // حفظات أقدم من الخاتمة: الفصل المكتمل يعني أن أثره صار جزءًا من العالم.
    EPI_KEYS.forEach((k) => {
      if (s.postQuests[k] === 'done') s.flags['epi_' + k] = true;
    });
    const p = s.postProgress;
    if (!Array.isArray(p.carved)) p.carved = [];
    if (!Array.isArray(p.planted)) p.planted = [];
    ['names', 'lanterns', 'wheel', 'saplings'].forEach((k) => {
      if (typeof p[k] !== 'number' || isNaN(p[k])) {
        p[k] = k === 'names' ? p.carved.length : k === 'saplings' ? p.planted.length : 0;
      }
    });
    return s;
  }
  St.epiState = epiState;

  // ملخّص واحد تستخدمه الواجهة والسجلّ والخريطة.
  St.epilogueStats = function (s) {
    s = epiState(s) || {};
    const p = s.postProgress || {};
    const done = EPI_KEYS.filter((q) => s.postQuests && s.postQuests[q] === 'done').length;
    const stats = {
      done,
      total: EPI_KEYS.length,
      ready: done >= EPI_KEYS.length,
      ceremony: !!s.flags.epilogueDone,
      names: p.carved || [],
      lanterns: p.lanterns || 0,
      wheel: p.wheel || 0,
      saplings: p.saplings || 0,
      steps: {},
    };
    EPI_KEYS.forEach((q) => {
      const d = D.postQuests[q] || {};
      const st = (s.postQuests || {})[q];
      const value = st === 'done' ? (d.steps || 1)
        : q === 'names' ? stats.names.length
          : q === 'garden' ? stats.saplings
            : q === 'lanterns' ? stats.lanterns
              : stats.wheel;
      stats.steps[q] = { state: st || 'offered', value, total: d.steps || 1 };
    });
    return stats;
  };

  // وصف نموّ الحديقة — يتغيّر مع عدد فصول الخاتمة المكتملة.
  St.gardenMood = function (stats) {
    const n = stats ? stats.done : 0;
    if (n >= 4) return 'أربع شتلات، وأوراقٌ خضراء، وواحدة أورقت زهرة صغيرة.';
    if (n >= 2) return 'الشتلات كبرت، وأوراقها الأولى تفتّحت.';
    return 'الشتلات صغيرة، بالكاد تُرى بين الرماد.';
  };

  async function finishEpi(qid) {
    const g = A.game, s = epiState();
    if (!s || s.postQuests[qid] === 'done') return;
    s.postQuests[qid] = 'done';
    s.flags['epi_' + qid] = true;
    const pq = D.postQuests[qid] || {};
    g.apply({ rep: pq.rep || 2 });
    g.toast('أتممتَ: ' + (pq.name || '') + ' — +' + A.fmt(pq.rep || 2) + ' سمعة', 'good');
    const stats = St.epilogueStats(s);
    if (stats.ready && !s.flags.epilogueReady) {
      s.flags.epilogueReady = true;
      await g.play([
        N('أربع مهام صغيرة. لا سيوف، ولا حصون، ولا أيام. فقط أشياء كان يجب أن تُفعل منذ زمن.'),
        N('حين تعود إلى دير النار، تجد الناس ينتظرونك عند النار. لا أحد يقول شيئًا. لا أحد يحتاج أن يقول.'),
      ]);
      g.awardTrophy('afterwar');
      g.toast('اكتملت خاتمة المملكة — عد إلى نار دير النار.', 'trophy');
    }
    g.save();
  }

