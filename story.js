  St.warCouncil = async function () {
    const g = A.game, s = g.state;
    // آخر حوار مع النقيب عادل: السور نفسه يتحرّك خلف الكلام.
    g.mode = 'scene';
    g.setBg('siege', [
      { kind: 'hero', x: 196, y: 214, s: 1.85, pose: 'idle', opts: g.heroOpts(), bob: true },
    ]);
    A.audio.ambient('war');
    await g.play([
      N('الفجر الأخير. من سور قلعة الشمس، ترى الغبار يتقدّم كأنه جدارٌ يسير.'),
      SAY('captain', 'ساعة. ربما أقل.'),
      H('هل وصل كل شيء؟'),
      SAY('captain', 'كل ما أرسلته. الباقي… على الله.'),
      N('ينظر إلى يديك، إلى السيف أو القوس.'),
      SAY('captain', 'كيف تريد أن تقاتل؟'),
    ]);

    // التجهيز يحدّد لغة المجلس: سورٌ ممتلئ أم صفٌّ فارغ.
    const war = g.warSupply ? g.warSupply() : { ratio: 0 };
    if (war.ratio < 0.45) {
      await g.play([
        N('تصعد إلى السور. الصناديق فارغة، والرماح بلا رؤوس، والجرحى بلا ضمادات.'),
        SAY('captain', 'هذا كل ما جمعناه؟ إذًا لن نُقاتل طويلًا.'),
        N(s.jinnDeal || s.flags.jinnArmy
          ? 'على التلّ، نار الجنّ تخبو ثم تنطفئ. لا أحد يقاتل من أجل جدارٍ خالٍ.'
          : 'لا حلفاء، ولا مؤونة. فقط الصمت، والغبار القادم.'),
        SAY('captain', 'إن كنتَ ستقاتل… قاتل كأنك وحدك.'),
      ]);
    } else if (war.ratio < 0.8) {
      await g.play([
        N('على السور، صناديق نصف ممتلئة، ورماحٌ كافية… بالكاد.'),
        SAY('captain', 'صمدنا بأقلّ من اللازم. لا تُهدر شيئًا.'),
      ]);
    }

    const opts = [
      OPT('القوس.', { sub: 'من بعيد، قبل أن يصلوا' }),
      OPT('السيف.', { sub: 'وجهاً لوجه، في القلب' }),
      OPT('المنجنيق.', { sub: 'حجرٌ يسحق مجموعة', req: (st) => st.flags.catapult, reqText: 'المنجنيق ما زال مكسورًا' }),
    ];
    const c = await g.ask(opts);
    s.battleChoice = ['bow', 'sword', 'catapult'][c];
    let res = null;
    const championHp = 58 - (s.flags.zainabTruth ? 14 : 0) - (s.flags.sidraLantern ? 6 : 0) + Math.round(war.ratio * 12);

    if (s.battleChoice === 'bow') {
      await g.play([
        N('تصعد إلى البرج. القوس في يدك أثقل من ذكرياتك.'),
        SAY('hunter', 'خذ نفسًا. السهم يعرف متى يخرج.'),
      ]);
      res = await A.battle.bowGame({ final: true });
      await g.play([
        N(res.win
          ? 'ثلاث موجات من المشاة تنكسر عند السور. للمرة الأولى منذ أسبوع، يتراجع العدوّ خطوة.'
          : 'تنكسر موجة… وتأتي أخرى. عند الموجة ' + A.fmt(res.waveReached || 1) + ' تمرّ السهام بينهم ويصل الصفّ إلى السور.'),
      ]);
    } else if (s.battleChoice === 'sword') {
      await g.play([
        N('تنزل إلى البوابة. أمامك، فارسٌ بدرعٍ أسود يمشي بين الجنود كأنهم ظلّه.'),
        SAY('champion', 'أنت؟'),
        H('أنا.'),
        ...(s.flags.zainabTruth ? [
          N('تتذكّر خيط زينب الأحمر. الدرع لا يُكسر… يُفتح.'),
          H('تحت الذراع اليسرى.'),
        ] : []),
        ...(s.flags.sidraLantern ? [
          N('ضوء فانوس سيدرا يرتجف على الدرع الأسود، فيكشف خيطًا رقيقًا عند الكتف.'),
          H('الضوء يعرف طريقه.'),
        ] : []),
        N('يرفع سيفه. الرماد يلتفّ حول النصل.'),
      ]);
      res = await A.battle.gauntlet([
        { enemy: 'ashRaider', hp: 24 + Math.round(war.ratio * 10) },
        { enemy: 'ashCaptain', hp: 38 + Math.round(war.ratio * 14) },
        { enemy: 'champion', hp: championHp },
      ], { final: true, tint: 'rgba(120,20,20,.18)' });
      await g.play([
        N(res.win
          ? 'ثلاث موجات. يسقط آخر ناهب، ثم قائد الكتيبة، ثم قائد الرماد نفسه. الجيش يتراجع كموجةٍ فقدت قمرها.'
          : (res.fled
            ? 'تتراجع بين الموجات. تبقى أسماءُ من سقطوا خلفك، والسور يصمد… بصعوبة.'
            : 'تُسحب من المعركة عند الموجة ' + A.fmt(res.waveReached || 1) + '. الموجات التالية تعبر فوق من بقي.')),
      ]);
    } else {
      await g.play([
        N('تدير ذراع المنجنيق. الحجر الذي فيه كان جزءًا من السور.'),
        N('على التلّ، مجموعات المشاة تتقدّم صفًّا بعد صفّ. كل حجر يسقط ثلاثة.'),
        SAY('mason', 'الطاقة بين الخمسين والثمانين. لا ترمِ وأنت غاضب.'),
      ]);
      res = await A.battle.catapultGame({ final: true });
      await g.play([
        N(res.win
          ? 'ثلاث موجات من المشاة تتقدّم، وفي كل مرة يسقط صفٌّ كامل من ثلاثة. الغبار يغطّي الساحة، والجيش يتوقف ليحصي خسائره.'
          : 'تسقط مجموعات، وتتقدّم أخرى. عند الموجة ' + A.fmt(res.waveReached || 1) + ' تمرّ الحجارة فوق رؤوسهم.'),
      ]);
    }

    await g.finishBattle(res);
  };

