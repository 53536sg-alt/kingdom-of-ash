  St.epilogue = function (tier, flags) {
    const out = [];
    if (tier === 'sacrifice') {
      out.push('في اليوم الثلاثين، استردّ الجنّ سنواتهم الأربع، وتجمّع البحر الأسود على سور المملكة.');
      out.push('قاتلت المملكة معك: قوسًا يشدّ، وسيفًا يُشهر، وحجرًا يُقذف. ثم خرجتَ وحدك، وأُغلقت البوابة خلفك لأن من أحبّوك رفضوا أن يضيّعوا ما اشتريته.');
      out.push('وحين سقطتَ، أظلمت السماء بسهام المملكة، فلم يقف من جيش الرماد أحد.');
      out.push('انكسر جيش الرماد على بابٍ فقد حارسه. صمدت كالدَر. وحدها كالدَر.');
      out.push('لم ترَ الفجر. لكن في ساحة المملكة رُفع لك تمثال، والملك نفسه يقف أمامه. وكل طفلٍ وُلد في ذلك الصباح سيعرف أن رجلًا أو امرأةً وقفت هنا، ولم تتراجع.');
    } else if (tier === 'best') {
      out.push('عند الفجر، سقطت إمبراطورية الرماد على أسوار قلعة الشمس.');
      out.push('لكن الأسماء التي لا تُحصى بقيت في الرماد. كالدَر لم تنتصر… بل نجت.');
      out.push('أعاد الناس بناء دير النار. لم يعد أحدٌ يسألك عن الفحم. صرت «الذي عاد».');
    } else if (tier === 'good') {
      out.push('صمدت قلعة الشمس. نصف المدينة احترق، ونصفها الآخر يبكي من بقي.');
      out.push('دفعت الإمبراطورية ثمنًا لم تتوقعه. لكنها ستعود، بعد جيلٍ أو جيلين.');
      out.push('بينك وبين السلام، وقفتَ أنت. لا أحد يعرف كم كلّفك ذلك.');
    } else if (tier === 'neutral') {
      out.push('لم تسقط كالدَر، ولم تنتصر. صارت ولايةً تدفع الجزية، وتحتفظ بأسمائها.');
      out.push('قالوا إن هذا سلام. أنت تعرف أنه صبرٌ طويل.');
      out.push('كل ليلة، يطفئ أهل دير النار نارهم مبكرًا، كأنهم يخفون شيئًا.');
    } else {
      out.push('سقطت قلعة الشمس في اليوم الثلاثين.');
      out.push('دخلت إمبراطورية الرماد المدينة، ولم تُبقِ سوى الأسماء.');
      out.push('أنت نجوت. تحمل فحمًا، وتسمع أخبار الطرق. الحكاية لم تنتهِ… لكن المملكة انتهت.');
    }
    if (flags.priceName) out.push('\nنسوا اسمك. صار الناس ينادونك «الذي عاد». وفي الليل، تسمع الجنّ ينادونك باسمٍ لا تعرفه.');
    if (flags.priceShadow) out.push('\nلم يعد لك ظلّ. وفي كل صباح، تتذكّر أن ذراعك ليست القوية التي كانت.');
    if (flags.priceNight) out.push('\nنسيت أول ليلة من عمرك، وكل ليلة بعدها صارت أطول.');
    if (flags.mercy) out.push('\nتركتَ قائد الرماد حيًّا. لم يفهم لماذا. أنت أيضًا لم تفهم تمامًا.');
    if (flags.twist) out.push('\nأنهيتَ أمر قائد الرماد بفتلة. لم يصرخ، لكن النصل الذي يُدار يُذكر أطول.');
    else if (flags.execute) out.push('\nأنهيتَ أمر قائد الرماد. يقولون إن الرماد لا ينسى.');
    if (flags.peace) out.push('\nأرسلتَ رسالة إلى قيصر الرماد: «لنا أسماء، وأنتم تملكون رمادًا. لنتفاوض». ولم يأتِ الجواب بعد.');
    if (flags.jinnChild && flags.voteFrost) out.push('\nفي بعض الليالي، يزورك نُوّار. لا يتكلم، فقط يجلس قرب النار حتى تنام.');
    if (flags.ashRing) out.push('\nالخاتم ما زال في إصبعك. أحيانًا، حين تصمت المدينة، تسمعه يهمس.');
    return out.join('\n');
  };

